"""Bundle a song analysis folder into analysis.js for pages opened as local files (file:// can't fetch JSON).

  python3 song-bundle.py <analysis dir> <audio path relative to tray/> [title]

Writes analysis.js: window.SONG_ANALYSIS = {title, audio, summary, features, cues}. November 16, 2026.
"""
import sys, os, json
d, audio = sys.argv[1], sys.argv[2]
title = sys.argv[3] if len(sys.argv) > 3 else ''
load = lambda n: json.load(open(os.path.join(d, n))) if os.path.exists(os.path.join(d, n)) else None
bundle = {'title': title, 'audio': audio, 'summary': load('summary.json'), 'features': load('features.json'), 'cues': load('cues.json')}
open(os.path.join(d, 'analysis.js'), 'w').write('// Generated by the Coast\'s scripts/song-bundle.py. See README.md in this folder.\nwindow.SONG_ANALYSIS = ' + json.dumps(bundle, separators=(',', ':')) + ';\n')
print('analysis.js', os.path.getsize(os.path.join(d, 'analysis.js')) // 1024, 'KB')
